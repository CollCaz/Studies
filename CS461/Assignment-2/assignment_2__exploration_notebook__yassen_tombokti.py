df_raw = pd.read_csv("Food_Delivery_Times/Food_Delivery_Times.csv")
df_raw.head()

"""## Exploring the Data"""

df = df_raw.copy()
df.info()
print(df.isna().sum())
print(df[df.isna().any(axis=1)])
print(df.isna().mean().sort_values(ascending=False))
print(len(df), len(df.dropna()))
# since I would lose too much data if I remove nulls, I will fill nulls with the median

df["Courier_Experience_yrs"] = df["Courier_Experience_yrs"].fillna(df["Courier_Experience_yrs"].median())
for col in ["Weather", "Time_of_Day", "Traffic_Level"]:
    df[col] = df[col].fillna(df[col].mode()[0])

print(df.isna().sum())

numerical_cols = [
    "Distance_km",
    "Preparation_Time_min",
    "Courier_Experience_yrs",
    "Delivery_Time_min",
]

print("=== Descriptive Statistics ===")
print(df[numerical_cols].describe().to_string())

print("\n=== Potential Outliers (IQR Method) ===")
for col in numerical_cols:
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1

    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR

    outliers = df[(df[col] < lower) | (df[col] > upper)][col]

    print(f"\n{col}:")
    print(f"  Lower bound: {lower:.2f}")
    print(f"  Upper bound: {upper:.2f}")
    print(f"  Number of potential outliers: {len(outliers)}")
    print(f"  Outlier values: {sorted(outliers.tolist())}")

# traffic level remains a single column because each category is more of the same
df["Traffic_Level"] = df["Traffic_Level"].map({"Low": 0, "Medium": 1, "High": 2})
print(df["Traffic_Level"].value_counts(dropna=False))

# the rest of the text data needs to be split into dummy columns because
# the categories are not steps, but actual categories
X = pd.get_dummies(df.drop(columns=["Order_ID", "Delivery_Time_min"]), drop_first=True, dtype=int)
y = df["Delivery_Time_min"]

print(X.shape)             # expect (1000, 13)
print(X.isna().sum().sum())  # expect 0

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=0)

# made no difference in accuracy
scaler = MinMaxScaler()
X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# Uses ordinary least squares (OLS) by default so I don't to configure that
model = LinearRegression()
model.fit(X_train, y_train)

train_pred = model.predict(X_train)
pred = model.predict(X_test)

print("Training MAE:", mean_absolute_error(y_train, train_pred))
print("Training RMSE:", np.sqrt(mean_squared_error(y_train, train_pred)))
print("Train MAE:", mean_absolute_error(y_train, train_pred))
print("Test MAE:", mean_absolute_error(y_test, pred))

plt.scatter(y_test, pred, alpha=0.7)

# Perfect prediction reference line
low = min(y_test.min(), pred.min())
high = max(y_test.max(), pred.max())
plt.plot([low, high], [low, high], "r--", label="Perfect prediction")

plt.xlabel("Real values")
plt.ylabel("Predicted values")
plt.title("Real vs. Predicted Values")
plt.legend()
plt.grid(True, alpha=0.3)
plt.show()